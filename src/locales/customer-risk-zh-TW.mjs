export function localizeCustomerRiskPage(english) {
  let html = english;
  for (const [source, translated, expected = 1] of copy) {
    const count = html.split(source).length - 1;
    if (count !== expected) throw Error(`Customer Risk zh-TW source mismatch: ${source} (${count}, expected ${expected})`);
    html = html.replaceAll(source, translated);
  }
  return html;
}
